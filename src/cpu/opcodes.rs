use super::addressing_modes::AddressingMode::{self, *};
use super::instructions::Instruction::{self, *};

/// Decodes an opcode into (instruction, addressing mode, base cycles).
/// Base cycles assume 8-bit registers and DL = 0; the CPU adds the rest.
pub fn decode(opcode: u8) -> (Instruction, AddressingMode, u8) {
    match opcode {
        // Exceptions inside the ALU group below
        0x89 => (BIT, ImmediateA, 2),
        0x91 => (STA, DirectIndirectIndexed, 6),
        0x99 => (STA, AbsoluteIndexedY, 5),
        0x9D => (STA, AbsoluteIndexedX, 5),

        // ALU group: opcode bits 7-5 pick the instruction, bits 4-0 the mode.
        // Odd opcodes plus $x2 in odd rows, except the $xB column.
        op if op & 0x0F != 0x0B && (op & 0x01 == 1 || op & 0x1F == 0x12) => {
            let ins = [ORA, AND, EOR, ADC, STA, LDA, CMP, SBC][(op >> 5) as usize];
            let (mode, cycles) = match op & 0x1F {
                0x01 => (DirectIndexedIndirect, 6),
                0x03 => (StackRelative, 4),
                0x05 => (Direct, 3),
                0x07 => (DirectIndirectLong, 6),
                0x09 => (ImmediateA, 2),
                0x0D => (Absolute, 4),
                0x0F => (AbsoluteLong, 5),
                0x11 => (DirectIndirectIndexed, 5),
                0x12 => (DirectIndirect, 5),
                0x13 => (StackRelativeIndexedIndirect, 7),
                0x15 => (DirectIndexedX, 4),
                0x17 => (DirectIndirectLongIndexed, 6),
                0x19 => (AbsoluteIndexedY, 4),
                0x1D => (AbsoluteIndexedX, 4),
                _ => (AbsoluteLongIndexedX, 5), // 0x1F
            };
            (ins, mode, cycles)
        }

        0x00 => (BRK, Implied, 7),
        0x02 => (COP, Implied, 7),
        0x04 => (TSB, Direct, 5),
        0x06 => (ASL, Direct, 5),
        0x08 => (PHP, Implied, 3),
        0x0A => (ASL, Accumulator, 2),
        0x0B => (PHD, Implied, 4),
        0x0C => (TSB, Absolute, 6),
        0x0E => (ASL, Absolute, 6),
        0x10 => (BPL, Relative, 2),
        0x14 => (TRB, Direct, 5),
        0x16 => (ASL, DirectIndexedX, 6),
        0x18 => (CLC, Implied, 2),
        0x1A => (INC, Accumulator, 2),
        0x1B => (TCS, Implied, 2),
        0x1C => (TRB, Absolute, 6),
        0x1E => (ASL, AbsoluteIndexedX, 7),

        0x20 => (JSR, Absolute, 6),
        0x22 => (JSL, AbsoluteLong, 8),
        0x24 => (BIT, Direct, 3),
        0x26 => (ROL, Direct, 5),
        0x28 => (PLP, Implied, 4),
        0x2A => (ROL, Accumulator, 2),
        0x2B => (PLD, Implied, 5),
        0x2C => (BIT, Absolute, 4),
        0x2E => (ROL, Absolute, 6),
        0x30 => (BMI, Relative, 2),
        0x34 => (BIT, DirectIndexedX, 4),
        0x36 => (ROL, DirectIndexedX, 6),
        0x38 => (SEC, Implied, 2),
        0x3A => (DEC, Accumulator, 2),
        0x3B => (TSC, Implied, 2),
        0x3C => (BIT, AbsoluteIndexedX, 4),
        0x3E => (ROL, AbsoluteIndexedX, 7),

        0x40 => (RTI, Implied, 6),
        0x42 => (WDM, Implied, 2),
        0x44 => (MVP, BlockMove, 7),
        0x46 => (LSR, Direct, 5),
        0x48 => (PHA, Implied, 3),
        0x4A => (LSR, Accumulator, 2),
        0x4B => (PHK, Implied, 3),
        0x4C => (JMP, Absolute, 3),
        0x4E => (LSR, Absolute, 6),
        0x50 => (BVC, Relative, 2),
        0x54 => (MVN, BlockMove, 7),
        0x56 => (LSR, DirectIndexedX, 6),
        0x58 => (CLI, Implied, 2),
        0x5A => (PHY, Implied, 3),
        0x5B => (TCD, Implied, 2),
        0x5C => (JML, AbsoluteLong, 4),
        0x5E => (LSR, AbsoluteIndexedX, 7),

        0x60 => (RTS, Implied, 6),
        0x62 => (PER, RelativeLong, 6),
        0x64 => (STZ, Direct, 3),
        0x66 => (ROR, Direct, 5),
        0x68 => (PLA, Implied, 4),
        0x6A => (ROR, Accumulator, 2),
        0x6B => (RTL, Implied, 6),
        0x6C => (JMP, AbsoluteIndirect, 5),
        0x6E => (ROR, Absolute, 6),
        0x70 => (BVS, Relative, 2),
        0x74 => (STZ, DirectIndexedX, 4),
        0x76 => (ROR, DirectIndexedX, 6),
        0x78 => (SEI, Implied, 2),
        0x7A => (PLY, Implied, 4),
        0x7B => (TDC, Implied, 2),
        0x7C => (JMP, AbsoluteIndexedIndirect, 6),
        0x7E => (ROR, AbsoluteIndexedX, 7),

        0x80 => (BRA, Relative, 2),
        0x82 => (BRL, RelativeLong, 3),
        0x84 => (STY, Direct, 3),
        0x86 => (STX, Direct, 3),
        0x88 => (DEY, Implied, 2),
        0x8A => (TXA, Implied, 2),
        0x8B => (PHB, Implied, 3),
        0x8C => (STY, Absolute, 4),
        0x8E => (STX, Absolute, 4),
        0x90 => (BCC, Relative, 2),
        0x94 => (STY, DirectIndexedX, 4),
        0x96 => (STX, DirectIndexedY, 4),
        0x98 => (TYA, Implied, 2),
        0x9A => (TXS, Implied, 2),
        0x9B => (TXY, Implied, 2),
        0x9C => (STZ, Absolute, 4),
        0x9E => (STZ, AbsoluteIndexedX, 5),

        0xA0 => (LDY, ImmediateXY, 2),
        0xA2 => (LDX, ImmediateXY, 2),
        0xA4 => (LDY, Direct, 3),
        0xA6 => (LDX, Direct, 3),
        0xA8 => (TAY, Implied, 2),
        0xAA => (TAX, Implied, 2),
        0xAB => (PLB, Implied, 4),
        0xAC => (LDY, Absolute, 4),
        0xAE => (LDX, Absolute, 4),
        0xB0 => (BCS, Relative, 2),
        0xB4 => (LDY, DirectIndexedX, 4),
        0xB6 => (LDX, DirectIndexedY, 4),
        0xB8 => (CLV, Implied, 2),
        0xBA => (TSX, Implied, 2),
        0xBB => (TYX, Implied, 2),
        0xBC => (LDY, AbsoluteIndexedX, 4),
        0xBE => (LDX, AbsoluteIndexedY, 4),

        0xC0 => (CPY, ImmediateXY, 2),
        0xC2 => (REP, Implied, 3),
        0xC4 => (CPY, Direct, 3),
        0xC6 => (DEC, Direct, 5),
        0xC8 => (INY, Implied, 2),
        0xCA => (DEX, Implied, 2),
        0xCB => (WAI, Implied, 3),
        0xCC => (CPY, Absolute, 4),
        0xCE => (DEC, Absolute, 6),
        0xD0 => (BNE, Relative, 2),
        0xD4 => (PEI, Direct, 6),
        0xD6 => (DEC, DirectIndexedX, 6),
        0xD8 => (CLD, Implied, 2),
        0xDA => (PHX, Implied, 3),
        0xDB => (STP, Implied, 3),
        0xDC => (JML, AbsoluteIndirectLong, 6),
        0xDE => (DEC, AbsoluteIndexedX, 7),

        0xE0 => (CPX, ImmediateXY, 2),
        0xE2 => (SEP, Implied, 3),
        0xE4 => (CPX, Direct, 3),
        0xE6 => (INC, Direct, 5),
        0xE8 => (INX, Implied, 2),
        0xEA => (NOP, Implied, 2),
        0xEB => (XBA, Implied, 3),
        0xEC => (CPX, Absolute, 4),
        0xEE => (INC, Absolute, 6),
        0xF0 => (BEQ, Relative, 2),
        0xF4 => (PEA, Absolute, 5),
        0xF6 => (INC, DirectIndexedX, 6),
        0xF8 => (SED, Implied, 2),
        0xFA => (PLX, Implied, 4),
        0xFB => (XCE, Implied, 2),
        0xFC => (JSR, AbsoluteIndexedIndirect, 8),
        0xFE => (INC, AbsoluteIndexedX, 7),

        _ => unreachable!("all 256 opcodes are listed above"),
    }
}
